CREATE TABLE workspace_note (
 id VARCHAR(36) NOT NULL PRIMARY KEY,
 project_id VARCHAR(36) NULL,
 event_id VARCHAR(36) NULL,
 partnership_id VARCHAR(36) NULL,
 meeting_id VARCHAR(36) NULL,
 author_id VARCHAR(36) NOT NULL,
 title VARCHAR(200) NOT NULL,
 body TEXT NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP(6) NOT NULL,
 updated_at TIMESTAMP(6) NOT NULL,
 removed_at TIMESTAMP(6) NULL,
 CONSTRAINT note_project_fk FOREIGN KEY(project_id) REFERENCES project(id),
 CONSTRAINT note_event_fk FOREIGN KEY(event_id) REFERENCES community_event(id),
 CONSTRAINT note_partnership_fk FOREIGN KEY(partnership_id) REFERENCES partnership(id),
 CONSTRAINT note_meeting_fk FOREIGN KEY(meeting_id) REFERENCES meeting(id),
 CONSTRAINT note_author_fk FOREIGN KEY(author_id) REFERENCES app_user(id),
 CONSTRAINT note_context_ck CHECK((project_id IS NOT NULL)+(event_id IS NOT NULL)+(partnership_id IS NOT NULL)+(meeting_id IS NOT NULL)=1),
 INDEX note_project_idx(project_id,removed_at,updated_at),
 INDEX note_event_idx(event_id,removed_at,updated_at),
 INDEX note_partnership_idx(partnership_id,removed_at,updated_at),
 INDEX note_meeting_idx(meeting_id,removed_at,updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
